"""LLM_RAG v0.9.5 — local command-line chat for existing SFT checkpoints.

Supports RoPE (v0.9.3+) and legacy Attention. Uses the exact original
'前:...\\n問:...\\n答:' prompt and a sliding two-turn history. It is NOT a
retrieval pipeline: chat responses are generated by the local language model.
No training, network access, file writes or automatic memory storage.
"""
from __future__ import annotations

import argparse
import random
import sys
from pathlib import Path

from prepare_real_persona_v081 import compact_prompt
from rag_persona import LocalRAG


def make_prompt(question: str, history: list[str], tokenizer,
                context_length: int, max_new_tokens: int = 48,
                evidence: str = "") -> tuple[str, list[str]]:
    """Drop oldest WHOLE turns until prompt fits; never truncate the question.

    Leave a generation budget when possible. Our model can slide its context
    window during generation, so not all generated tokens need to fit in the
    initial window, but a nonempty budget prevents immediate eviction.
    """
    if not isinstance(question, str) or not question.strip():
        raise ValueError("Question must not be empty")
    if max_new_tokens < 1:
        raise ValueError("max_new_tokens must be >=1")
    kept = list(history[-2:])
    evidence_text = evidence.strip()
    while True:
        ctx = "／".join([*kept, *((["資料:" + evidence_text]) if evidence_text else [])])
        prompt = compact_prompt({"question": question.strip(), "context": ctx})
        ids = tokenizer.encode(prompt, add_bos=True)
        if len(ids) < context_length and len(ids) + min(max_new_tokens, 16) <= context_length:
            return prompt, kept
        if kept:
            kept.pop(0)
            continue
        if evidence_text:
            # Keep question intact; shorten retrieved context if necessary.
            evidence_text = evidence_text[:max(0, len(evidence_text) // 2)]
            continue
        if len(ids) >= context_length:
            raise ValueError(
                f"Question too long for context_length={context_length}: "
                f"prompt_tokens={len(ids)}; shorten the input."
            )
        return prompt, kept


def decode_answer(model, tokenizer, prompt: str, *, max_new_tokens: int = 48,
                  temperature: float = 0.0, top_k: int = 40,
                  repetition_penalty: float = 1.3) -> tuple[str, bool]:
    prompt_ids = tokenizer.encode(prompt, add_bos=True)
    if len(prompt_ids) >= model.context_length:
        raise ValueError("Prompt exceeds model context")
    with __import__("torch").inference_mode():
        seq = model.generate(
            prompt_ids, max_new_tokens=max_new_tokens,
            eos_id=tokenizer.eos_id, temperature=temperature,
            top_k=top_k if temperature > 0 else None,
            repetition_penalty=repetition_penalty)
    tail = seq[len(prompt_ids):]
    return tokenizer.decode(tail, skip_special_tokens=True), bool(
        tail and tail[-1] == tokenizer.eos_id)


def resolve_rope(encoding: str, checkpoint_config: dict) -> bool:
    marker = checkpoint_config.get("position_encoding", "none")
    if marker not in ("none", "rope_v093", "rope_v096_mha"):
        raise ValueError(f"Unsupported position encoding {marker!r}")
    if encoding == "auto":
        return marker != "none"
    if encoding == "legacy":
        wanted = "none"
    elif encoding == "rope":
        wanted = "rope_v093"
    elif encoding == "mha":
        wanted = "rope_v096_mha"
    else:
        raise ValueError("encoding must be auto|legacy|rope|mha")
    if marker != wanted:
        raise ValueError("Requested attention is incompatible with checkpoint")
    return marker != "none"


def load_chat(args):
    import torch
    sys.path.insert(0, str(args.gpu_dir.resolve()))
    from tokenizer import Tokenizer
    from mha_rope_v096 import load_model_v096, checkpoint_architecture

    device = torch.device(
        "cuda" if args.device == "auto" and torch.cuda.is_available()
        else "cpu" if args.device == "auto" else args.device)
    # Only locally trusted checkpoints should be loaded with torch.load.
    checkpoint = torch.load(str(args.checkpoint), map_location="cpu", weights_only=True)
    encoding = resolve_rope(args.encoding, checkpoint["config"])
    architecture, heads = checkpoint_architecture(checkpoint["config"])
    model, _ = load_model_v096(args.checkpoint, device, expected=architecture,
                              mha_heads=heads)
    tokenizer = Tokenizer.load(str(args.tokenizer))
    if model.vocab_size != tokenizer.vocab_size:
        raise ValueError("Checkpoint and tokenizer vocabulary mismatch")
    model.eval()
    return model, tokenizer, str(device), encoding


def run(args) -> None:
    if (args.max_new_tokens < 1 or args.temperature < 0 or args.top_k < 1
            or args.top_k_docs < 1 or args.evidence_chars < 1):
        raise ValueError("Invalid generation options")
    if args.repetition_penalty <= 0:
        raise ValueError("repetition-penalty must be positive")
    import torch
    torch.manual_seed(args.seed)
    random.seed(args.seed)
    model, tok, device, rope = load_chat(args)
    print("=" * 64)
    print(" LLM_RAG v0.9.6 — Local Chat")
    print("=" * 64)
    print(f"Model     : {args.checkpoint}")
    print(f"Attention : {'Multi-Head RoPE (' + str(model.num_heads) + ' heads)' if getattr(model, 'num_heads', 1) > 1 else ('RoPE' if rope else 'Legacy')}")
    print(f"Device    : {device}")
    print(f"Context   : {model.context_length}, Parameters: {model.parameter_count:,}")
    print("Commands  : /reset  /status  /reload  /sources  /exit")
    print("Note: local generative SFT demo, not an evidence-grounded retrieval answer.")
    history: list[str] = []
    rag = LocalRAG(args.docs) if args.rag else None
    sources: list[str] = []
    if rag:
        print(f"RAG       : on, docs={args.docs}, passages={len(rag.passages)}")
    else:
        print("RAG       : off (use --rag to enable local retrieval)")
    while True:
        try:
            question = input("You> ").strip()
        except (EOFError, KeyboardInterrupt):
            print("\n終了します。")
            break
        if not question:
            continue
        if question.lower() in ("/exit", "/quit"):
            break
        if question == "/reset":
            history.clear()
            sources.clear()
            print("History cleared.")
            continue
        if question == "/status":
            print(f"History turns={len(history)}, max=2; model_context={model.context_length}, RAG={bool(rag)}")
            continue
        if question == "/reload":
            if not rag:
                print("RAG disabled. Restart with --rag.")
            else:
                rag.refresh()
                print(f"RAG: {len(rag.passages)} passages reloaded.")
            continue
        if question == "/sources":
            print("Sources: " + (", ".join(sources) if sources else "none"))
            continue
        if question.startswith("/"):
            print("Unknown command. Available: /reset /status /reload /sources /exit")
            continue
        try:
            hits = rag.search(question, k=args.top_k_docs) if rag else []
            sources = [hit.source for hit in hits]
            # Short evidence, not trusted as a system instruction or fact.
            snippets = [hit.text[:args.evidence_chars] for hit in hits]
            prompt, _ = make_prompt(question, history, tok,
                                    model.context_length, args.max_new_tokens,
                                    evidence="／".join(snippets))
            answer, eos = decode_answer(
                model, tok, prompt, max_new_tokens=args.max_new_tokens,
                temperature=args.temperature, top_k=args.top_k,
                repetition_penalty=args.repetition_penalty)
        except ValueError as exc:
            print(f"Input rejected: {exc}")
            continue
        display = answer.strip() or "(生成できませんでした)"
        print(f"AI> {display}")
        if sources:
            print("RAG sources (unverified): " + ", ".join(sources))
        # Keep the real model output, not the display placeholder.
        history.extend((question, answer))
        history = history[-2:]
        if args.verbose:
            print(f"[EOS={eos}, prompt_tokens={len(tok.encode(prompt, add_bos=True))}, history_turns={len(history)}]")


def main():
    p = argparse.ArgumentParser(description="Local conversational CLI for LLM_RAG models")
    p.add_argument("--gpu-dir", type=Path, default=Path("../LLM_GPU"))
    p.add_argument("--tokenizer", type=Path, default=Path("../LLM_GPU/model/tokenizer.json"))
    p.add_argument("--checkpoint", type=Path,
                   default=Path("model/model-rag-rope-legacy-v0.9.3.pt"))
    p.add_argument("--device", choices=("auto", "cpu", "cuda"), default="auto")
    p.add_argument("--encoding", choices=("auto", "legacy", "rope", "mha"), default="auto")
    p.add_argument("--max-new-tokens", type=int, default=48)
    p.add_argument("--temperature", type=float, default=0.0)
    p.add_argument("--top-k", type=int, default=40)
    p.add_argument("--repetition-penalty", type=float, default=1.3)
    p.add_argument("--seed", type=int, default=42)
    p.add_argument("--rag", action="store_true",
                   help="Optional local document retrieval; model was not trained for grounded citations")
    p.add_argument("--docs", type=Path, default=Path("data/knowledge"))
    p.add_argument("--top-k-docs", type=int, default=1)
    p.add_argument("--evidence-chars", type=int, default=32)
    p.add_argument("--verbose", action="store_true")
    run(p.parse_args())


if __name__ == "__main__":
    main()
