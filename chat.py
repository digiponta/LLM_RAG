"""LLM_RAG v0.10.13 — local CLI with Nagato named-entity direct evidence.

Supports RoPE (v0.9.3+) and legacy Attention. Uses the exact original
'前:...\\n問:...\\n答:' prompt and a sliding two-turn history. It is NOT a
retrieval pipeline: chat responses are generated by the local language model.
No training, network access, file writes or automatic memory storage.
"""
from __future__ import annotations

import argparse
import random
import sys
from pathlib import Path

from prepare_real_persona_v081 import compact_prompt
from evaluate_evidence_position_v104 import position_question
from prepare_generalized_copy_v103 import QUESTION as COPY_QUESTION
from rag_persona import LocalRAG
from nagato_direct_v1013 import NagatoDirect


def make_prompt(question: str, history: list[str], tokenizer,
                context_length: int, max_new_tokens: int = 48,
                evidence: str = "") -> tuple[str, list[str]]:
    """Drop oldest WHOLE turns until prompt fits; never truncate the question.

    Leave a generation budget when possible. Our model can slide its context
    window during generation, so not all generated tokens need to fit in the
    initial window, but a nonempty budget prevents immediate eviction.
    """
    if not isinstance(question, str) or not question.strip():
        raise ValueError("Question must not be empty")
    if max_new_tokens < 1:
        raise ValueError("max_new_tokens must be >=1")
    kept = list(history[-2:])
    evidence_text = evidence.strip()
    while True:
        ctx = "／".join([*kept, *((["資料:" + evidence_text]) if evidence_text else [])])
        prompt = compact_prompt({"question": question.strip(), "context": ctx})
        ids = tokenizer.encode(prompt, add_bos=True)
        if len(ids) < context_length and len(ids) + min(max_new_tokens, 16) <= context_length:
            return prompt, kept
        if kept:
            kept.pop(0)
            continue
        if evidence_text:
            # Keep question intact; shorten retrieved context if necessary.
            evidence_text = evidence_text[:max(0, len(evidence_text) // 2)]
            continue
        if len(ids) >= context_length:
            raise ValueError(
                f"Question too long for context_length={context_length}: "
                f"prompt_tokens={len(ids)}; shorten the input."
            )
        return prompt, kept


def decode_answer(model, tokenizer, prompt: str, *, max_new_tokens: int = 48,
                  temperature: float = 0.0, top_k: int = 40,
                  repetition_penalty: float = 1.3) -> tuple[str, bool]:
    prompt_ids = tokenizer.encode(prompt, add_bos=True)
    if len(prompt_ids) >= model.context_length:
        raise ValueError("Prompt exceeds model context")
    with __import__("torch").inference_mode():
        seq = model.generate(
            prompt_ids, max_new_tokens=max_new_tokens,
            eos_id=tokenizer.eos_id, temperature=temperature,
            top_k=top_k if temperature > 0 else None,
            repetition_penalty=repetition_penalty)
    tail = seq[len(prompt_ids):]
    return tokenizer.decode(tail, skip_special_tokens=True), bool(
        tail and tail[-1] == tokenizer.eos_id)



CHAT_MODES = ("chat", "knowledge", "persona", "evidence")
POSITION_LIMIT = 10


def parse_position_command(value: str) -> tuple[int, str]:
    """Parse /position N TEXT; only 10-char evidence matched the trained task."""
    parts = value.split(maxsplit=2)
    if len(parts) != 3 or parts[0] != "/position":
        raise ValueError("Usage: /position N TEXT (exactly 10 characters)")
    try:
        pos = int(parts[1])
    except ValueError as exc:
        raise ValueError("Position must be 1, 5 or 10") from exc
    if pos not in (1, 5, 10):
        raise ValueError("Position must be 1, 5 or 10 (trained positions)")
    evidence = parts[2]
    if len(evidence) != POSITION_LIMIT:
        raise ValueError("For the trained task, TEXT must contain exactly 10 characters")
    return pos, evidence


def position_prompt(position: int, evidence: str) -> str:
    if position not in (1, 5, 10) or len(evidence) != POSITION_LIMIT:
        raise ValueError("Position prompt accepts positions 1/5/10 and 10 characters")
    return compact_prompt({
        "question": position_question(position),
        "context": "資料:" + evidence,
    })


def copy_prompt(evidence: str) -> str:
    """Use the explicit generalized-copy task, without pretending exact success."""
    if not evidence or len(evidence) != POSITION_LIMIT:
        raise ValueError("Usage: /copy TEXT (exactly 10 characters)")
    return compact_prompt({"question": COPY_QUESTION,
                           "context": "資料:" + evidence})


def resolve_rope(encoding: str, checkpoint_config: dict) -> bool:
    marker = checkpoint_config.get("position_encoding", "none")
    if marker not in ("none", "rope_v093", "rope_v096_mha"):
        raise ValueError(f"Unsupported position encoding {marker!r}")
    if encoding == "auto":
        return marker != "none"
    if encoding == "legacy":
        wanted = "none"
    elif encoding == "rope":
        wanted = "rope_v093"
    elif encoding == "mha":
        wanted = "rope_v096_mha"
    else:
        raise ValueError("encoding must be auto|legacy|rope|mha")
    if marker != wanted:
        raise ValueError("Requested attention is incompatible with checkpoint")
    return marker != "none"


def load_chat(args):
    import torch
    sys.path.insert(0, str(args.gpu_dir.resolve()))
    from tokenizer import Tokenizer
    from mha_rope_v096 import load_model_v096, checkpoint_architecture
    from intent_model_v097 import load_intent_model

    device = torch.device(
        "cuda" if args.device == "auto" and torch.cuda.is_available()
        else "cpu" if args.device == "auto" else args.device)
    # Only locally trusted checkpoints should be loaded with torch.load.
    checkpoint = torch.load(str(args.checkpoint), map_location="cpu", weights_only=True)
    encoding = resolve_rope(args.encoding, checkpoint["config"])
    architecture, heads = checkpoint_architecture(checkpoint["config"])
    if checkpoint["config"].get("auxiliary_head") == "dialogue_intent_v097":
        if architecture != "rope":
            raise ValueError("Intent head is supported only for single-head RoPE")
        model, _ = load_intent_model(args.checkpoint, device)
    else:
        model, _ = load_model_v096(args.checkpoint, device, expected=architecture,
                                  mha_heads=heads)
    tokenizer = Tokenizer.load(str(args.tokenizer))
    if model.vocab_size != tokenizer.vocab_size:
        raise ValueError("Checkpoint and tokenizer vocabulary mismatch")
    model.eval()
    return model, tokenizer, str(device), encoding


def run(args) -> None:
    if (args.max_new_tokens < 1 or args.temperature < 0 or args.top_k < 1
            or args.top_k_docs < 1 or args.evidence_chars < 1):
        raise ValueError("Invalid generation options")
    if args.repetition_penalty <= 0:
        raise ValueError("repetition-penalty must be positive")
    import torch
    torch.manual_seed(args.seed)
    random.seed(args.seed)
    model, tok, device, rope = load_chat(args)
    print("=" * 64)
    print(" LLM_RAG v0.10.13 — Unified Local Chat")
    print("=" * 64)
    print(f"Model     : {args.checkpoint}")
    print(f"Attention : {'Multi-Head RoPE (' + str(model.num_heads) + ' heads)' if getattr(model, 'num_heads', 1) > 1 else ('RoPE' if rope else 'Legacy')}")
    print(f"Device    : {device}")
    print(f"Context   : {model.context_length}, Parameters: {model.parameter_count:,}")
    print("Commands  : /mode [chat|knowledge|persona|evidence]  /position N TEXT  /copy TEXT")
    print("            /reset  /status  /reload  /sources  /exit")
    print("Note: frozen v0.10.11 research checkpoint, not independently validated dialogue quality.")
    print("      Proper-name hits in data-nagato.txt return one original sentence, bypassing LLM.")
    print("      /position follows trained examples; /copy is not yet reliable.")
    history: list[str] = []
    mode = "chat"
    rag = LocalRAG(args.docs) if args.rag else None
    direct = (NagatoDirect(args.nagato_source, entity_file=args.nagato_entities)
              if args.nagato_direct else None)
    sources: list[str] = []
    if direct:
        print(f"Nagato    : direct={direct.available}, source={direct.source}, "
              f"sentences={len(direct.entries)}, entities={len(direct.names)}")
    else:
        print("Nagato    : direct match off")
    if rag:
        print(f"RAG       : on, docs={args.docs}, passages={len(rag.passages)}")
    else:
        print("RAG       : off (use --rag to enable local retrieval)")
    while True:
        try:
            question = input("You> ").strip()
        except (EOFError, KeyboardInterrupt):
            print("\n終了します。")
            break
        if not question:
            continue
        if question.lower() in ("/exit", "/quit"):
            break
        if question == "/reset":
            history.clear()
            sources.clear()
            print("History cleared.")
            continue
        if question == "/status":
            print(f"History turns={len(history)}, max=2; mode={mode}; "
                  f"model_context={model.context_length}, RAG={bool(rag)}, "
                  f"checkpoint={args.checkpoint}, nagato_direct={bool(direct and direct.available)}")
            continue
        if question == "/reload":
            if direct:
                direct.refresh()
                print(f"Nagato direct: {len(direct.entries)} sentences reloaded.")
            if rag:
                rag.refresh()
                print(f"RAG: {len(rag.passages)} passages reloaded.")
            if not direct and not rag:
                print("No retrieval sources enabled.")
            continue
        if question == "/sources":
            print("Sources: " + (", ".join(sources) if sources else "none"))
            continue
        if question.startswith("/mode"):
            pieces = question.split()
            if len(pieces) == 1:
                print(f"Mode: {mode}; choices: {', '.join(CHAT_MODES)}")
            elif len(pieces) == 2 and pieces[1] in CHAT_MODES:
                mode = pieces[1]
                history.clear()
                sources.clear()
                print(f"Mode changed to {mode}; history cleared.")
            else:
                print("Usage: /mode chat|knowledge|persona|evidence")
            continue
        if question.startswith("/") and not (
                question.startswith("/position ") or question.startswith("/copy ")):
            print("Unknown command. Use /mode /position /copy /reset /status /reload /sources /exit")
            continue
        special = question.startswith("/position ") or question.startswith("/copy ")
        # Direct source-quotation path runs BEFORE RAG/LLM generation.
        # The literal hit is a statement in the local corpus, not verified truth.
        if not special and direct:
            hit = direct.find(question)
            if hit is not None:
                sources = [hit.source]
                print(f"AI> {hit.sentence}")
                print(f"[Nagato direct quote: entity={hit.entity}, "
                      f"source={hit.source}:{hit.line_number}; "
                      "source statement, not independently verified; LLM bypassed]")
                history.extend((question, hit.sentence))
                history = history[-2:]
                continue
        try:
            if question.startswith("/position "):
                pos, text = parse_position_command(question)
                prompt = position_prompt(pos, text)
                token_budget = min(4, args.max_new_tokens)
                # Match frozen Position benchmark decoding: no repetition penalty.
                answer, eos = decode_answer(
                    model, tok, prompt, max_new_tokens=token_budget,
                    temperature=0.0, repetition_penalty=1.0)
                sources = []
            elif question.startswith("/copy "):
                evidence = question[len("/copy "):]
                prompt = copy_prompt(evidence)
                answer, eos = decode_answer(
                    model, tok, prompt, max_new_tokens=min(32, args.max_new_tokens),
                    temperature=0.0, repetition_penalty=1.0)
                sources = []
            else:
                hits = rag.search(question, k=args.top_k_docs) if rag else []
                sources = [hit.source for hit in hits]
                snippets = [hit.text[:args.evidence_chars] for hit in hits]
                effective_question = question
                if mode == "knowledge":
                    effective_question = "長門コーパスの記述に基づいて、出典を明示して答えてください。" + question
                elif mode == "persona":
                    effective_question = "長門として次の問いに答えてください。" + question
                elif mode == "evidence":
                    effective_question = "提示資料で確認できることだけを答えてください。" + question
                prompt, _ = make_prompt(
                    effective_question, history, tok,
                    model.context_length, args.max_new_tokens,
                    evidence="／".join(snippets))
                answer, eos = decode_answer(
                    model, tok, prompt, max_new_tokens=args.max_new_tokens,
                    temperature=args.temperature, top_k=args.top_k,
                    repetition_penalty=args.repetition_penalty)
        except ValueError as exc:
            print(f"Input rejected: {exc}")
            continue
        display = answer.strip() or "(生成できませんでした)"
        print(f"AI> {display}")
        if question.startswith("/copy "):
            print("[Experimental COPY: v0.10.11 DEVELOPMENT exact-copy=0/200. Do not treat as verified.]")
        if question.startswith("/position "):
            print("[Experimental POSITION: v0.10.11 DEVELOPMENT exact=58.67%, not guaranteed.]")
        if mode == "evidence" and not special and not sources:
            print("[No retrieved evidence; generated answer is unverified.]")
        if args.show_intent and hasattr(model, "intent_head"):
            import torch
            from intent_model_v097 import INTENTS
            with torch.inference_mode():
                prompt_ids = torch.tensor(
                    [tok.encode(prompt, add_bos=True)], device=next(model.parameters()).device,
                    dtype=torch.long)
                _, logits = model.forward_with_intent(
                    prompt_ids, torch.tensor([prompt_ids.shape[1]-1], device=prompt_ids.device))
                probabilities = torch.softmax(logits[0], dim=-1)
                label = int(probabilities.argmax().item())
                print(f"[Intent (weak supervision): {INTENTS[label]}, confidence={probabilities[label]:.3f}; "
                      "not a fact/answer validity judgment]")
        if sources:
            print("RAG sources (unverified): " + ", ".join(sources))
        # Keep the real model output, not the display placeholder.
        if not special:
            history.extend((question, answer))
            history = history[-2:]
        if args.verbose:
            print(f"[EOS={eos}, prompt_tokens={len(tok.encode(prompt, add_bos=True))}, history_turns={len(history)}]")


def main():
    p = argparse.ArgumentParser(description="Local conversational CLI for LLM_RAG models")
    p.add_argument("--gpu-dir", type=Path, default=Path("../LLM_GPU"))
    p.add_argument("--tokenizer", type=Path, default=Path("../LLM_GPU/model/tokenizer.json"))
    p.add_argument("--checkpoint", type=Path,
                   default=Path("model/model-rag-position-rehearsal-v0.10.11.pt"))
    p.add_argument("--device", choices=("auto", "cpu", "cuda"), default="auto")
    p.add_argument("--encoding", choices=("auto", "legacy", "rope", "mha"), default="auto")
    p.add_argument("--max-new-tokens", type=int, default=48)
    p.add_argument("--temperature", type=float, default=0.0)
    p.add_argument("--top-k", type=int, default=40)
    p.add_argument("--repetition-penalty", type=float, default=1.3)
    p.add_argument("--seed", type=int, default=42)
    p.add_argument("--nagato-source", type=Path,
                   default=Path("data/knowledge/data-nagato.txt"),
                   help="Original Nagato corpus for literal one-sentence direct matches")
    p.add_argument("--nagato-entities", type=Path, default=None,
                   help="Optional local UTF-8 entity lexicon, one name per line")
    p.add_argument("--no-nagato-direct", action="store_false", dest="nagato_direct",
                   help="Disable original sentence priority; always use normal RAG/LLM")
    p.set_defaults(nagato_direct=True)
    p.add_argument("--rag", action="store_true",
                   help="Optional local document retrieval; model was not trained for grounded citations")
    p.add_argument("--docs", type=Path, default=Path("data/knowledge"))
    p.add_argument("--top-k-docs", type=int, default=1)
    p.add_argument("--evidence-chars", type=int, default=32)
    p.add_argument("--show-intent", action="store_true",
                   help="Print experimental weakly trained intent prediction when available")
    p.add_argument("--verbose", action="store_true")
    run(p.parse_args())


if __name__ == "__main__":
    main()
